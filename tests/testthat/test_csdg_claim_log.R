test_that("the claim log records claims, checks, assessments, and tests on new data", {
  csdg_claim_log_reset()
  expect_identical(nrow(csdg_claim_log()), 0L)
  expect_named(csdg_claim_log(), c("entry", "time", "function_name", "claim_id", "kind", "statement", "quantity",
    "learners", "task_id", "n_rows", "n_features", "data_hash", "origin", "result"))
  imp = make_importance_fixture(labels = c(m1 = "XGBoost"))
  claim = claim_relies_mainly(imp, k = 2)
  res = csdg_assess(csdg_check(claim, imp))
  conf = csdg_confirm(csdg_check(claim, imp, judgments = g0b_judged()), make_importance_fixture(data_hash = "new_data"))
  log = csdg_claim_log()
  expect_identical(log$function_name, c("claim_relies_mainly", "csdg_check", "csdg_assess", "csdg_check",
    "csdg_confirm"))
  expect_identical(log$entry, 1:5)
  expect_identical(unique(log$statement), "XGBoost relies mainly on a and b.")
  expect_identical(unique(log$learners), "XGBoost")
  expect_identical(unique(log$quantity), "pfi")
  expect_identical(log$data_hash, c(rep("fixture_data", 4L), "new_data"))
  expect_identical(unique(log$n_rows), 400L)
  expect_identical(unique(log$n_features), 4L)
  expect_true(is.na(log$result[[1L]]))
  expect_identical(log$result[[2L]], "open: G0b; supported: G0a, G2, G5")
  expect_identical(log$result[[3L]], "unresolved (exploratory)")
  expect_identical(log$result[[5L]], "met (tested on new data)")
  expect_identical(log$origin, c(rep("exploratory", 4L), "tested on new data"))
  expect_s3_class(log$time, "POSIXct")
  log$statement[[1L]] = "changed"
  expect_identical(csdg_claim_log()$statement[[1L]], "XGBoost relies mainly on a and b.")
  old = csdg_claim_log_reset()
  expect_identical(nrow(old), 5L)
  expect_identical(nrow(csdg_claim_log()), 0L)
})

test_that("the claim log records each derived claim once", {
  csdg_claim_log_reset()
  imp = make_importance_fixture()
  claim_top_k(imp, k = 1)
  claim_order(imp, "a", "b")
  suppressWarnings(claim_relies_mainly(imp, predictors = c("a", "c")))
  log = csdg_claim_log()
  expect_identical(log$function_name, c("claim_top_k", "claim_order", "claim_relies_mainly"))
  expect_identical(log$kind, c("top_k", "order", "relies_mainly"))
  expect_error(claim_order(imp, "a", "a"), "different")
  expect_identical(nrow(csdg_claim_log()), 3L)
})
